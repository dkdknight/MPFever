"""Writes launcher/gameopts.json: the 0.6 game options the feature modules declare (mod/mpfever_1/content/mpfever_feat_*.lua,
through the real options host mpfever_feat.lua), for the dedicated server's settings window (launcher/ServerSettings.cs), which
shows them without the game. Each option: its id, its module, its company modes, its title and description in French and
English, its parameters with their label, default and values (each value as the options string writes it and as the lobby shows
it, in both languages). The other languages come from lang.json at run time (keyed by the English text, as every T(fr, en)).

    python tools/gen_gameopts.py           writes the file
    python tools/gen_gameopts.py --check   exit code 1 when the file is not the one the modules give (tests/test_serversettings.py)
"""
import json
import os
import sys

import lupa.lua52 as lupa

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
CONTENT = os.path.join(ROOT, "mod", "mpfever_1", "content")
OUT = os.path.join(ROOT, "launcher", "gameopts.json")


def catalog():
    L = lupa.LuaRuntime(unpack_returned_tuples=True)
    g = L.globals()
    g.CONTENT = CONTENT.replace("\\", "/")
    F = L.execute(r'''
        local function file(name)
            local f = assert(io.open(CONTENT .. "/" .. name, "rb"))
            local s = f:read("*a")
            f:close()
            return assert(load(s, "@" .. name))()
        end
        local F = file("mpfever_feat.lua")
        F.loader = function(id)
            local ok, m = pcall(file, "mpfever_feat_" .. id .. ".lua")
            if ok and type(m) == "table" then return m end
            return nil
        end
        F.load(function() end)
        return F
    ''')
    run = L.eval('''function(F)
        local TF = function(fr, en) return fr end
        local TE = function(fr, en) return en end
        local function pair(p)
            if p == nil then return nil end
            return { F.text(p, TF), F.text(p, TE) }
        end
        local out = {}
        for _, e in ipairs(F.offered(nil)) do
            local o = e.opt
            local ps = {}
            for _, p in ipairs(e.params) do
                local vs = {}
                for _, v in ipairs(p.values) do
                    vs[#vs + 1] = { v = tostring(v), fr = F.showValue(p, v, TF), en = F.showValue(p, v, TE) }
                end
                ps[#ps + 1] = { id = p.id, label = pair(p.label or p.id), default = tostring(p.default), perPlayer = p.perPlayer == true, values = vs }
            end
            out[#out + 1] = { id = o.id, module = e.M.ID, modes = o.modes or "both", title = pair(o.title or o.id), desc = pair(o.desc), params = ps }
        end
        return out
    end''')
    res = run(F)

    def py(x):
        if lupa.lua_type(x) == "table":
            keys = list(x.keys())
            if keys and all(isinstance(k, int) for k in keys) and sorted(keys) == list(range(1, len(keys) + 1)):
                return [py(x[k]) for k in range(1, len(keys) + 1)]
            return {k: py(x[k]) for k in sorted(keys)}
        return x
    return {"about": "Generated by tools/gen_gameopts.py from the feature modules: do not edit by hand.", "options": py(res)}


def text(cat):
    return json.dumps(cat, ensure_ascii=False, indent=1, sort_keys=True) + "\n"


def main():
    want = text(catalog())
    if "--check" in sys.argv:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have.replace("\r\n", "\n") != want:
            print("launcher/gameopts.json is not up to date: run python tools/gen_gameopts.py")
            return 1
        print("launcher/gameopts.json up to date")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(want)
    n = len(json.loads(want)["options"])
    print(f"{OUT}: {n} options")
    return 0


if __name__ == "__main__":
    sys.exit(main())
